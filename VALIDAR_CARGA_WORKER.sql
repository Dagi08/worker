-- ============================================================
-- SAGI - Validación de la carga del worker (AGT_SAGI_BT_*)
-- Ejecutar en Snowsight por bloques. Cambiar la instancia en el SET.
-- ============================================================
USE SCHEMA DB_DEV.SC_SLV_RIESGOS;
SET V_INST = 123456;          -- instancia (IdSolicitudCredito) a revisar

-- ------------------------------------------------------------
-- 1) Últimas instancias cargadas: filas por tabla
--    Compara con la línea del log del worker:
--    "IdSolicitudCredito=N cargado en Snowflake: {'PERSONA': 1, 'SOLICITUD': 1, ...}"
-- ------------------------------------------------------------
SELECT S.INSTANCIA, S.NUMERO_DOCUMENTO, S.FECHA_CARGA,
       (SELECT COUNT(*) FROM AGT_SAGI_BT_PERSONA P             WHERE P.NUMERO_DOCUMENTO = S.NUMERO_DOCUMENTO) AS PERSONA,
       (SELECT COUNT(*) FROM AGT_SAGI_BT_EMPLEO X              WHERE X.INSTANCIA = S.INSTANCIA) AS EMPLEO,
       (SELECT COUNT(*) FROM AGT_SAGI_BT_DOMICILIO X           WHERE X.NUMERO_DOCUMENTO = S.NUMERO_DOCUMENTO) AS DOMICILIO,
       (SELECT COUNT(*) FROM AGT_SAGI_BT_PERSONA_CUENTA X      WHERE X.NUMERO_DOCUMENTO = S.NUMERO_DOCUMENTO) AS PERSONA_CUENTA,
       (SELECT COUNT(*) FROM AGT_SAGI_BT_MOROSIDAD_OPERACION M
          JOIN AGT_SAGI_BT_PERSONA_CUENTA C ON C.CUENTA = M.CUENTA
         WHERE C.NUMERO_DOCUMENTO = S.NUMERO_DOCUMENTO)                                         AS MOROSIDAD,
       (SELECT COUNT(*) FROM AGT_SAGI_BT_INGRESO_DETALLE X     WHERE X.INSTANCIA = S.INSTANCIA) AS INGRESO_DETALLE,
       (SELECT COUNT(*) FROM AGT_SAGI_BT_DEUDA_FINANCIERA X    WHERE X.INSTANCIA = S.INSTANCIA) AS DEUDA_FINANCIERA,
       (SELECT COUNT(*) FROM AGT_SAGI_BT_INDICADOR_FINANCIERO X WHERE X.INSTANCIA = S.INSTANCIA) AS INDICADOR_FIN,
       (SELECT COUNT(*) FROM AGT_SAGI_BT_RCI X                 WHERE X.INSTANCIA = S.INSTANCIA) AS RCI,
       (SELECT COUNT(*) FROM AGT_SAGI_BT_VEHICULO X            WHERE X.INSTANCIA = S.INSTANCIA) AS VEHICULO
  FROM AGT_SAGI_BT_SOLICITUD S
 ORDER BY S.FECHA_CARGA DESC
 LIMIT 20;

-- ------------------------------------------------------------
-- 2) Detalle de una instancia
-- ------------------------------------------------------------
SELECT * FROM AGT_SAGI_BT_SOLICITUD WHERE INSTANCIA = $V_INST;
SELECT P.* FROM AGT_SAGI_BT_PERSONA P
  JOIN AGT_SAGI_BT_SOLICITUD S ON S.NUMERO_DOCUMENTO = P.NUMERO_DOCUMENTO WHERE S.INSTANCIA = $V_INST;
SELECT * FROM AGT_SAGI_BT_VEHICULO         WHERE INSTANCIA = $V_INST;
SELECT * FROM AGT_SAGI_BT_EMPLEO           WHERE INSTANCIA = $V_INST;
SELECT * FROM AGT_SAGI_BT_INGRESO_DETALLE  WHERE INSTANCIA = $V_INST ORDER BY VARIABLE_PERIODO, CATEGORIA;
SELECT * FROM AGT_SAGI_BT_DEUDA_FINANCIERA WHERE INSTANCIA = $V_INST ORDER BY NRO_REGISTRO;
SELECT * FROM AGT_SAGI_BT_INDICADOR_FINANCIERO WHERE INSTANCIA = $V_INST;
SELECT * FROM AGT_SAGI_BT_RCI              WHERE INSTANCIA = $V_INST;
SELECT D.* FROM AGT_SAGI_BT_DOMICILIO D
  JOIN AGT_SAGI_BT_SOLICITUD S ON S.NUMERO_DOCUMENTO = D.NUMERO_DOCUMENTO WHERE S.INSTANCIA = $V_INST;
SELECT C.NUMERO_DOCUMENTO, M.* FROM AGT_SAGI_BT_PERSONA_CUENTA C
  JOIN AGT_SAGI_BT_SOLICITUD S ON S.NUMERO_DOCUMENTO = C.NUMERO_DOCUMENTO
  LEFT JOIN AGT_SAGI_BT_MOROSIDAD_OPERACION M ON M.CUENTA = C.CUENTA
 WHERE S.INSTANCIA = $V_INST;

-- ------------------------------------------------------------
-- 3) Variables que necesita el modelo (si sale algo en FALTA, el modelo no tendrá puntaje)
-- ------------------------------------------------------------
SELECT S.INSTANCIA, S.NUMERO_DOCUMENTO,
       IFF(P.NUMERO_DOCUMENTO IS NULL, 'FALTA', P.TIPO_DOCUMENTO)          AS TIPO_DOCUMENTO,
       IFF(P.SEXO IS NULL, 'FALTA', P.SEXO)                                AS SEXO,
       IFF(P.FECHA_NACIMIENTO IS NULL, 'FALTA', P.FECHA_NACIMIENTO::STRING) AS FECHA_NACIMIENTO,
       IFF(S.SCORE IS NULL, 'FALTA', S.SCORE)                              AS SCORE_ADMISION,
       IFF(V.MODELO IS NULL OR TRIM(V.MODELO) IN ('', '-'), 'FALTA', V.MODELO) AS MODELO_VEHICULO,
       (SELECT LISTAGG(DISTINCT M.MONEDA, ',') FROM AGT_SAGI_BT_PERSONA_CUENTA C
          JOIN AGT_SAGI_BT_MOROSIDAD_OPERACION M ON M.CUENTA = C.CUENTA
         WHERE C.NUMERO_DOCUMENTO = S.NUMERO_DOCUMENTO)                    AS MONEDA_MOROSIDAD   -- vacío = usa PEN por defecto
  FROM AGT_SAGI_BT_SOLICITUD S
  LEFT JOIN AGT_SAGI_BT_PERSONA  P ON P.NUMERO_DOCUMENTO = S.NUMERO_DOCUMENTO
  LEFT JOIN AGT_SAGI_BT_VEHICULO V ON V.INSTANCIA = S.INSTANCIA
 ORDER BY S.FECHA_CARGA DESC
 LIMIT 20;

-- ------------------------------------------------------------
-- 4) Consistencia
-- ------------------------------------------------------------
-- 4.1 Solicitudes sin persona (debe salir 0)
SELECT S.INSTANCIA, S.NUMERO_DOCUMENTO FROM AGT_SAGI_BT_SOLICITUD S
  LEFT JOIN AGT_SAGI_BT_PERSONA P ON P.NUMERO_DOCUMENTO = S.NUMERO_DOCUMENTO
 WHERE P.NUMERO_DOCUMENTO IS NULL;

-- 4.2 Hijas sin solicitud (debe salir 0; Snowflake no obliga las FK)
SELECT 'VEHICULO' T, INSTANCIA FROM AGT_SAGI_BT_VEHICULO WHERE INSTANCIA NOT IN (SELECT INSTANCIA FROM AGT_SAGI_BT_SOLICITUD)
UNION ALL SELECT 'EMPLEO', INSTANCIA FROM AGT_SAGI_BT_EMPLEO WHERE INSTANCIA NOT IN (SELECT INSTANCIA FROM AGT_SAGI_BT_SOLICITUD)
UNION ALL SELECT 'INGRESO_DETALLE', INSTANCIA FROM AGT_SAGI_BT_INGRESO_DETALLE WHERE INSTANCIA NOT IN (SELECT INSTANCIA FROM AGT_SAGI_BT_SOLICITUD)
UNION ALL SELECT 'DEUDA_FINANCIERA', INSTANCIA FROM AGT_SAGI_BT_DEUDA_FINANCIERA WHERE INSTANCIA NOT IN (SELECT INSTANCIA FROM AGT_SAGI_BT_SOLICITUD)
UNION ALL SELECT 'INDICADOR_FINANCIERO', INSTANCIA FROM AGT_SAGI_BT_INDICADOR_FINANCIERO WHERE INSTANCIA NOT IN (SELECT INSTANCIA FROM AGT_SAGI_BT_SOLICITUD)
UNION ALL SELECT 'RCI', INSTANCIA FROM AGT_SAGI_BT_RCI WHERE INSTANCIA NOT IN (SELECT INSTANCIA FROM AGT_SAGI_BT_SOLICITUD);

-- 4.3 Duplicados (debe salir 0; Snowflake no obliga las PK)
SELECT 'SOLICITUD' T, INSTANCIA::STRING K, COUNT(*) N FROM AGT_SAGI_BT_SOLICITUD GROUP BY 1,2 HAVING N > 1
UNION ALL SELECT 'PERSONA', NUMERO_DOCUMENTO, COUNT(*) FROM AGT_SAGI_BT_PERSONA GROUP BY 1,2 HAVING COUNT(*) > 1
UNION ALL SELECT 'MOROSIDAD', OPERACION || '-' || CUENTA, COUNT(*) FROM AGT_SAGI_BT_MOROSIDAD_OPERACION GROUP BY 1,2 HAVING COUNT(*) > 1;

-- ------------------------------------------------------------
-- 5) ¿Se disparó el procesamiento después de la carga? (worker -> SP_SAGI_PROCESAR_INSTANCIA)
-- ------------------------------------------------------------
SELECT S.INSTANCIA, S.FECHA_CARGA,
       M.ESTADO AS MODELO, M.PUNTAJE, M.SCORE, M.MENSAJE AS MSG_MODELO,
       (SELECT MAX(E.FECHA_EJECUCION) FROM AGT_SAGI_EJECUCION E
         WHERE E.ID_SOLICITUD = 'INST-' || S.INSTANCIA)          AS WEB_SCRAPING,
       (SELECT MAX(C.DICTAMEN_PEP_PLAFT) FROM AGT_SAGI_COMPLIENCE C
         WHERE C.INSTANCIA = S.INSTANCIA)                        AS PEP_PLAFT,
       D.DICTAMEN, D.REGLA_APLICADA
  FROM AGT_SAGI_BT_SOLICITUD S
  LEFT JOIN AGT_SAGI_MODELO_RESULTADO M ON M.INSTANCIA = S.INSTANCIA
  LEFT JOIN AGT_SAGI_DICTAMEN D         ON D.INSTANCIA = S.INSTANCIA
 ORDER BY S.FECHA_CARGA DESC
 LIMIT 20;

-- Consultas del worker en Snowflake (cargas y CALL asíncronos) de las últimas 24 h
SELECT START_TIME, USER_NAME, EXECUTION_STATUS, ERROR_MESSAGE, LEFT(QUERY_TEXT, 150) AS QUERY
  FROM TABLE(INFORMATION_SCHEMA.QUERY_HISTORY(
         END_TIME_RANGE_START => DATEADD('hour', -24, CURRENT_TIMESTAMP()), RESULT_LIMIT => 1000))
 WHERE QUERY_TEXT ILIKE '%AGT_SAGI_BT_%' OR QUERY_TEXT ILIKE '%SP_SAGI_PROCESAR_INSTANCIA%'
 ORDER BY START_TIME DESC;
